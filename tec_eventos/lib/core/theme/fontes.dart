/// Define as fontes oficiais utilizadas na identidade visual do Tec!Eventos.
///
/// Mapeia os nomes das famílias de fontes configuradas no `pubspec.yaml`,
/// permitindo a aplicação consistente de estilos tipográficos no aplicativo.
class Fontes {
  Fontes._(); // Evita a instanciação da classe de utilitários

  /// Fonte principal elegante e moderna para cabeçalhos e títulos.
  static const String raleway = 'Raleway';

  /// Variação em negrito da Raleway, usada para textos em destaque e botões de chamada à ação.
  static const String ralewayBold = 'RalewayBold';

  /// Fonte alternativa limpa e geométrica para textos de leitura, tabelas e dados informativos.
  static const String inter = 'Inter';

  /// Variação em itálico da Cabin para descrições leves e citações.
  static const String cabinItalic = 'CabinItalic';

  /// Família tipográfica Cabin para subtítulos e rótulos de formulários secundários.
  static const String cabin = 'Cabin';
}
